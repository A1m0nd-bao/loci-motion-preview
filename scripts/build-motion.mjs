import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
await mkdir(new URL("../motion/vendor/", import.meta.url), { recursive: true });
await build({
  stdin: {
    contents: 'export { animate, hover, press, stagger, scroll } from "motion";',
    resolveDir: process.cwd(),
  },
  bundle: true, format: "esm", minify: true, target: "es2022", legalComments: "inline",
  outfile: new URL("../motion/vendor/motion.js", import.meta.url).pathname,
});
const demoSource = await readFile(new URL("../motion/demos.js", import.meta.url), "utf8");
const start = demoSource.indexOf("export function mountMotionDemo");
const end = demoSource.indexOf("export const motionDemoCSS", start);
if (start < 0 || end < 0) throw new Error("Motion demo factory not found");
await writeFile(new URL("../motion/export-source.js", import.meta.url), `// Generated by pnpm build:motion. Keep downloads independent of dev instrumentation.\nexport const motionDemoSource = ${JSON.stringify(demoSource.slice(start + 7, end).trim())};\n`);
console.log("Built standalone Motion 13.5.1 runtime for the public examples.");
